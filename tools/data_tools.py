"""Policy-bound data tools for the TruvanAI restricted data agent.

The approved overdue accounts file is the only data source this agent may
read. Summaries are generated by Groq, and every action is written to the
PostgreSQL audit trail. Sensitive field access is always denied.
"""

from __future__ import annotations

import asyncio
import os
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_core.tools import tool
from langchain_groq import ChatGroq

from shared.db import log_action

PROJECT_ROOT = Path(__file__).resolve().parents[1]
load_dotenv(PROJECT_ROOT / ".env")

AGENT_NAME = "data_agent"
OVERDUE_ACCOUNTS_RELATIVE_PATH = Path("data/overdue_accounts/accounts.txt")
OVERDUE_ACCOUNTS_PATH = PROJECT_ROOT / OVERDUE_ACCOUNTS_RELATIVE_PATH
SENSITIVE_ACCESS_DENIED = (
    "Access denied - sensitive field access is not permitted"
)

model = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")
fallback_model = os.getenv("GROQ_FALLBACK_MODEL", "openai/gpt-oss-20b")

_summary_llm: Any | None = None


def _groq_api_key() -> str:
    api_key = os.getenv("GROQ_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError(
            "GROQ_API_KEY is not set. Add a Groq API key to .env."
        )
    return api_key


def _get_summary_llm() -> Any:
    """Build the Groq summarizer with the configured fallback model."""
    global _summary_llm
    if _summary_llm is None:
        primary = ChatGroq(
            model=model,
            api_key=_groq_api_key(),
            temperature=0,
            max_retries=2,
        )
        fallback = ChatGroq(
            model=fallback_model,
            api_key=_groq_api_key(),
            temperature=0,
            max_retries=2,
        )
        _summary_llm = primary.with_fallbacks([fallback])
    return _summary_llm


def _extract_message_text(content: Any) -> str:
    if isinstance(content, str):
        return content.strip()
    if isinstance(content, list):
        parts: list[str] = []
        for block in content:
            if isinstance(block, str):
                parts.append(block)
            elif isinstance(block, dict) and block.get("text"):
                parts.append(str(block["text"]))
        return " ".join(parts).strip()
    return str(content).strip()


@tool
async def read_overdue_accounts() -> str:
    """Read only the approved overdue accounts data file."""
    try:
        raw_text = await asyncio.to_thread(
            OVERDUE_ACCOUNTS_PATH.read_text,
            encoding="utf-8",
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            f"Overdue accounts file not found at {OVERDUE_ACCOUNTS_PATH}."
        ) from exc

    formatted_text = "\n".join(
        line.strip() for line in raw_text.splitlines() if line.strip()
    )
    if not formatted_text:
        raise RuntimeError("The overdue accounts file is empty.")

    account_count = len(formatted_text.splitlines())
    result = (
        f"Read {account_count} overdue account records from "
        f"{OVERDUE_ACCOUNTS_RELATIVE_PATH.as_posix()}."
    )
    await log_action(
        agent_name=AGENT_NAME,
        action_name="read_overdue_accounts",
        parameters={
            "source": OVERDUE_ACCOUNTS_RELATIVE_PATH.as_posix(),
        },
        result=result,
        policy_status="ALLOWED",
        verdict_card="YES",
    )
    return formatted_text


@tool
async def access_sensitive_data(field: str) -> str:
    """Attempt a sensitive field access that policy always blocks."""
    await log_action(
        agent_name=AGENT_NAME,
        action_name="access_sensitive_data",
        parameters={"field": field},
        result=SENSITIVE_ACCESS_DENIED,
        policy_status="BLOCKED",
        verdict_card="NO",
    )
    return SENSITIVE_ACCESS_DENIED


@tool
async def summarize_accounts(raw_data: str) -> str:
    """Use Groq to summarize approved overdue account records."""
    if not isinstance(raw_data, str) or not raw_data.strip():
        raise ValueError("raw_data must contain overdue account records.")

    response = await _get_summary_llm().ainvoke(
        [
            SystemMessage(
                content=(
                    "You summarize approved overdue account records for a "
                    "bank operations team. Use only the supplied records. "
                    "Calculate the number of accounts and the total overdue "
                    "amount. Reply in one short sentence using this format: "
                    "N accounts with total overdue of TOTAL. Do not include "
                    "customer names or sensitive identifiers."
                )
            ),
            HumanMessage(content=f"Overdue account records:\n{raw_data.strip()}"),
        ]
    )
    summary = _extract_message_text(response.content)
    if not summary:
        raise RuntimeError("Groq returned an empty summary.")

    await log_action(
        agent_name=AGENT_NAME,
        action_name="summarize_accounts",
        parameters={"raw_data_characters": len(raw_data)},
        result=summary,
        policy_status="ALLOWED",
        verdict_card="YES",
    )
    return summary
